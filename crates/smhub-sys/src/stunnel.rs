//! HTTPS entries for app web UIs: one `app-<name>.conf` per installed app with a web port,
//! accepting on `port + 20000` and forwarding to the app (port of the old `core/iframe_proxy.py`).
//! Unlike the old code, stunnel is restarted only when a file actually changed.

use std::collections::{BTreeMap, BTreeSet};

use smhub_model::Result;

use crate::{Sys, fsx};

pub const CONF_DIR: &str = "/opt/smhub-services/config/stunnel.conf.d";
pub const OS_CONF: &str = "/etc/stunnel/stunnel.conf";
const OFFSET: u32 = 20_000;
const MIN_PORT: u32 = 1024;
const MAX_PORT: u32 = 65_535;
const PROBE_STEPS: u32 = 64;

/// An app with a web port, as the database records it.
#[derive(Debug, Clone)]
pub struct WebApp {
    pub key: String,
    pub port: u32,
    pub installed: bool,
}

fn parse_entries(text: &str) -> BTreeMap<String, u32> {
    let mut out = BTreeMap::new();
    let mut current: Option<String> = None;
    for line in text.lines() {
        let l = line.trim();
        if let Some(name) = l.strip_prefix("[app-").and_then(|r| r.strip_suffix(']')) {
            current = Some(name.to_owned());
        } else if l.starts_with('[') {
            current = None;
        } else if let (Some(app), Some(port)) = (&current, l.strip_prefix("accept = 0.0.0.0:")) {
            if let Ok(p) = port.trim().parse() {
                out.insert(app.clone(), p);
            }
        }
    }
    out
}

fn render(key: &str, port: u32, https: u32) -> String {
    format!("; Auto-generated by smhub-backend. Do not edit manually.\n[app-{key}]\naccept = 0.0.0.0:{https}\nconnect = 127.0.0.1:{port}\n")
}

fn next_port(base: u32, used: &BTreeSet<u32>) -> u32 {
    let (mut candidate, delta): (u32, i64) =
        if base + OFFSET > MAX_PORT { (MAX_PORT, -1) } else { (base + OFFSET, 1) };
    for _ in 0..PROBE_STEPS {
        if !(MIN_PORT..=MAX_PORT).contains(&candidate) {
            break;
        }
        if !used.contains(&candidate) && candidate != base {
            return candidate;
        }
        candidate = u32::try_from(i64::from(candidate) + delta).unwrap_or(MIN_PORT);
    }
    base
}

impl Sys {
    /// Static `[app-x]` entries in the OS's stunnel.conf, which win over generated ones.
    fn static_https_ports(&self) -> BTreeMap<String, u32> {
        std::fs::read_to_string(self.p(OS_CONF)).map(|t| parse_entries(&t)).unwrap_or_default()
    }

    fn generated_https_ports(&self) -> BTreeMap<String, u32> {
        let mut out = BTreeMap::new();
        if let Ok(rd) = std::fs::read_dir(self.p(CONF_DIR)) {
            for e in rd.flatten() {
                let name = e.file_name().to_string_lossy().into_owned();
                if name.starts_with("app-") && name.ends_with(".conf") {
                    if let Ok(t) = std::fs::read_to_string(e.path()) {
                        out.extend(parse_entries(&t));
                    }
                }
            }
        }
        out
    }

    /// HTTPS port of every app that has one.
    pub fn https_ports(&self) -> BTreeMap<String, u32> {
        let mut m = self.generated_https_ports();
        m.extend(self.static_https_ports());
        m
    }

    /// Bring the generated entries in line with the apps. Returns whether stunnel was restarted.
    pub async fn sync_stunnel(&self, apps: &[WebApp]) -> Result<bool> {
        let statics = self.static_https_ports();
        let on_disk = self.generated_https_ports();
        let mut used: BTreeSet<u32> = statics.values().copied().collect();
        let mut assigned: BTreeMap<String, u32> = BTreeMap::new();
        let eligible: BTreeMap<&str, u32> =
            apps.iter().filter(|a| a.installed && a.port > 0).map(|a| (a.key.as_str(), a.port)).collect();
        for (key, port) in &on_disk {
            if let Some(base) = eligible.get(key.as_str()) {
                if !statics.contains_key(key) && (MIN_PORT..=MAX_PORT).contains(port) && port != base && !used.contains(port) {
                    assigned.insert(key.clone(), *port);
                    used.insert(*port);
                }
            }
        }
        let dir = self.p(CONF_DIR);
        let mut changed = false;
        let mut sorted: Vec<&WebApp> = apps.iter().filter(|a| a.port > 0).collect();
        sorted.sort_by(|a, b| a.key.cmp(&b.key));
        for app in sorted {
            if statics.contains_key(&app.key) {
                continue;
            }
            // Like the old backend, apps that are not installed take a port too (in key order),
            // so an app gets the same port whatever else is installed.
            let https = match assigned.get(&app.key) {
                Some(p) => *p,
                None => {
                    let p = next_port(app.port, &used);
                    used.insert(p);
                    p
                }
            };
            if !eligible.contains_key(app.key.as_str()) {
                continue;
            }
            let file = dir.join(format!("app-{}.conf", app.key));
            let text = render(&app.key, app.port, https);
            if fsx::read_opt(&file)?.as_deref() != Some(text.as_str()) {
                fsx::write_plain(&file, text.as_bytes())?;
                changed = true;
            }
        }
        if let Ok(rd) = std::fs::read_dir(&dir) {
            for e in rd.flatten() {
                let name = e.file_name().to_string_lossy().into_owned();
                if let Some(key) = name.strip_prefix("app-").and_then(|n| n.strip_suffix(".conf")) {
                    if !eligible.contains_key(key) || statics.contains_key(key) {
                        let _ = std::fs::remove_file(e.path());
                        changed = true;
                    }
                }
            }
        }
        if changed && self.service_exists("stunnel") {
            self.service_action("stunnel", "restart").await?;
        }
        Ok(changed)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parse_and_ports() {
        let m = parse_entries("; x\n[app-zigbee2mqtt]\naccept = 0.0.0.0:28080\nconnect = 127.0.0.1:8080\n[ui]\naccept = 443\n");
        assert_eq!(m.get("zigbee2mqtt"), Some(&28080));
        assert_eq!(m.len(), 1);
        let used: BTreeSet<u32> = [28080].into_iter().collect();
        assert_eq!(next_port(8080, &used), 28081);
        assert_eq!(next_port(8787, &BTreeSet::new()), 28787);
        assert!(render("a", 1, 2).contains("accept = 0.0.0.0:2"));
    }
}
